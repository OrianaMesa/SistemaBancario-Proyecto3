    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
        // TODO add your handling code here:
         try {
        String numero = txtNumero.getText();
        String nombre = txtNombre.getText();

        int dia = Integer.parseInt(txtDia.getText());
        int mes = Integer.parseInt(txtMes.getText());
        int anio = Integer.parseInt(txtAnio.getText());

        double saldo = Double.parseDouble(txtSaldo.getText());

        if (numero.isEmpty() || nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el número y el nombre del dueño.");
            return;
        }

        if (dia < 1 || dia > 31 || mes < 1 || mes > 12 || anio < 1) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese una fecha válida.");
            return;
        }

        if (saldo < 0) {
            JOptionPane.showMessageDialog(this,
                    "El saldo no puede ser negativo.");
            return;
        }

        Fecha fecha = new Fecha(dia, mes, anio);
        boolean creada;

        if (cmbTipo.getSelectedItem().equals("Ahorros")) {
            creada = controlador.crearCuentaAhorros(
                    numero, nombre, fecha, saldo);
        } else {
            double cupo = Double.parseDouble(txtCupo.getText());

            if (cupo < 0) {
                JOptionPane.showMessageDialog(this,
                        "El cupo no puede ser negativo.");
                return;
            }

            creada = controlador.crearCuentaCorriente(
                    numero, nombre, fecha, saldo, cupo);
        }

        if (creada) {
            JOptionPane.showMessageDialog(this,
                    "Cuenta creada correctamente.");
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo crear. Verifique si el número ya existe.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Ingrese valores numéricos válidos.");
    }
    }//GEN-LAST:event_btnCrearActionPerformed

